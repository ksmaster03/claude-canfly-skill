# -*- coding: utf-8 -*-
"""
ตัวอย่างจริง — ย่อจากงาน NEW OFFICE GREENLAM (ตู้บิลท์อิน 10 ชุด)
แสดงครบทุกเคสที่เจอบ่อย: ตู้แยก BODY บน-ล่าง / ตู้ชนหลัง 2 หน้า / หลายชุดต่อกัน /
ตู้ช่องเก็บแผ่นตัวอย่าง / ตู้เข้ามุม L + ท็อปหิน

รัน:
    python example_project.py
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "scripts"))
from takeoff_lib import Takeoff

t = Takeoff()          # HMR 18 มม. / แผงหลัง 6 มม. / ชั้นร่น 30 มม.
T = t.T

# ---------------------------------------------------------------- 1) ตู้สูงแยก BODY บน-ล่าง
# 7650 x 500 x 2800 : 9 ช่อง ช่องละบานคู่ (บาน 422)
# สูงรวม = บังตา 100 + บานบน 1469 + คิ้วมือจับ 85 + บานล่าง 1096 + ตีนตู้ 50
W, D, CW, NC = 7650, 500, 822, 9
t.carcass("B1", W, 1146, D, NC, CW, n_shelf=2, prefix="ตู้ล่าง: ")
t.carcass("B1", W, 1569, D, NC, CW, n_shelf=3, prefix="ตู้บน: ")
t.P("B1", "หน้าบานล่าง", "HMR18", "GWE5101", "PW201P", 422, 1096, T, NC*2, edge=2*(422+1096))
t.P("B1", "หน้าบานบน",  "HMR18", "GSB107",  "PW201P", 422, 1469, T, NC*2, edge=2*(422+1469))
t.P("B1", "คิ้วมือจับในตัว", "HMR18", "GSB107", "-", W, 85,  T, 1, edge=W)
t.P("B1", "แผงบังตาบน",     "HMR18", "GSB107", "-", W, 100, T, 1, edge=W)
t.plinth("B1", W, D)
t.hw("B1", "บานพับ No Soft Close", "ตัว", NC*2*3 + NC*2*4)   # บาน<=1100 ใช้ 3 / >1100 ใช้ 4
t.hw("B1", "กุญแจล็อคหน้าบาน", "ชุด", NC*2)
t.hw("B1", "ขาปรับระดับ", "ตัว", NC*4)
t.hw("B1", "ตัวรองชั้นปรับระดับ", "ตัว", (NC*3 + NC*2)*4)

# ---------------------------------------------------------------- 2) ตู้เตี้ยธรรมดา
t.carcass("B3", 2000, 1050, 450, 5, 370, n_shelf=2)
t.P("B3", "หน้าบาน", "HMR18", "GWE5101", "PW201P", 390, 1090, T, 5, edge=2*(390+1090))
t.P("B3", "ท็อปบน",  "HMR18", "GWE5101", "PW201P", 2000, 450, T, 1, edge=2*(2000+450))
t.plinth("B3", 2000, 450)
t.hw("B3", "บานพับ No Soft Close", "ตัว", 15)
t.hw("B3", "ตัวรองชั้นปรับระดับ", "ตัว", 40)
t.hw("B3", "ขาปรับระดับ", "ตัว", 20)

# ---------------------------------------------------------------- 3) ตู้ชนหลัง 2 หน้า (ลึกรวม 900)
for side in ("ด้านหน้า", "ด้านหลัง"):
    t.carcass("B4", 2000, 1050, 450, 5, 370, n_shelf=2, prefix=f"{side}: ")
    t.P("B4", f"หน้าบาน {side}", "HMR18", "GWE5101", "PW201P",
        390, 1090, T, 5, edge=2*(390+1090))
t.P("B4", "ท็อปบน (ชิ้นเดียว ก.900)", "HMR18", "GWE5101", "PW201P",
    2000, 900, T, 1, edge=2*(2000+900))           # <- ท็อปชิ้นเดียว ไม่ใช่ 2 ชิ้น
t.plinth("B4", 2000, 900)
t.hw("B4", "บานพับ No Soft Close", "ตัว", 30)

# ---------------------------------------------------------------- 4) หลายชุดต่อกัน (โครงแยก)
for i in (1, 2):
    t.carcass("B5", 2400, 1050, 450, 6, 371, n_shelf=2, prefix=f"ชุดที่ {i}: ")
    t.P("B5", f"หน้าบาน ชุดที่ {i}", "HMR18", "GWE5101", "PW201P",
        392, 1090, T, 6, edge=2*(392+1090))
    t.P("B5", f"ท็อปบน ชุดที่ {i}", "HMR18", "GWE5101", "PW201P",
        2400, 450, T, 1, edge=2*(2400+450))
t.plinth("B5", 4800, 450, n_side=4)               # <- 2 ชุด = ตีนตู้ข้าง 4 แผง
t.hw("B5", "บานพับ No Soft Close", "ตัว", 36)

# ---------------------------------------------------------------- 5) ตู้ช่องเก็บแผ่นตัวอย่าง
# 7970 x 250 x 1200 : 142 ช่อง x 6 แถว = 852 ช่อง, แผ่นกั้น MDF 5 มม. ถอดได้
ROWS, PER_ROW, NSET = 6, 142, 6
t.P("B7", "แผงตั้งข้าง+กั้นชุด", "MDF16", "1401", "1401", 1084, 250, 16, NSET+1, edge=1084)
t.P("B7", "แผงบน",   "MDF16", "1401", "1401", 7970, 250, 16, 1, edge=2*(7970+250))
t.P("B7", "แผงล่าง", "MDF16", "1401", "1401", 7970, 250, 16, 1, edge=7970)
t.P("B7", "แผงหลัง", "MDF16", "1401", "-",    7970, 1084, 16, 1)
t.P("B7", "ชั้นวางแนวนอน (พ่นดำ)", "MDF16", "SPRAY_BK", "SPRAY_BK",
    7970, 234, 16, ROWS-1, edge=7970)
t.P("B7", "แผ่นกั้นช่อง ถอดได้", "MDF5", "1401", "1401",
    218, 130, 5, ROWS*PER_ROW, edge=130, note="852 ช่อง")
t.P("B7", "ตีนตู้", "MDF16", "1401", "-", 7970, 116, 16, 1, edge=7970)
t.P("B7", "พรมอัดรองพื้นช่อง", "FELT3", "-", "-", 7970, 218, 3, ROWS)
t.hw("B7", "ขาปรับระดับ", "ตัว", 24)

# ---------------------------------------------------------------- 6) เข้ามุม L + ท็อปหิน
t.carcass("B9", 2450, 750, 600, 4, 417, n_shelf=1, prefix="ตู้ล่าง: ")
t.carcass("B9", 2450, 1383, 400, 4, 417, n_shelf=2, prefix="ตู้บน: ")
t.P("B9", "หน้าบานล่าง", "HMR18", "GWE5101", "PW201P", 417, 732, T, 3, edge=2*(417+732))
t.P("B9", "หน้าบานบน",  "HMR18", "GSB107",  "PW201P", 417, 905, T, 3, edge=2*(417+905))
t.plinth("B9", 2450, 600)
t.P("B9", "ท็อปครัว หินเทียม 18 มม.",     "STONE", "-", "-", 2450, 600, 18, 1)
t.P("B9", "ผนังกันเปื้อน หินเทียม 18 มม.", "STONE", "-", "-", 2450, 650, 18, 1)  # <- อย่าลืม backsplash
t.hw("B9", "บานพับ No Soft Close", "ตัว", 18)

# ---------------------------------------------------------------- ออกไฟล์
ITEMS = {
    "B1": ("ตู้สูงเก็บเอกสาร (แยก BODY บน-ล่าง)", "7650 x 500 x 2800 มม."),
    "B3": ("ตู้เตี้ยเก็บแค็ตตาล็อค",              "2000 x 450 x 1200 มม."),
    "B4": ("ตู้เตี้ย 2 หน้า ชนหลัง",              "2000 x 900 x 1200 มม."),
    "B5": ("ตู้เตี้ย 2 ชุดต่อกัน",                "4800 x 450 x 1200 มม."),
    "B7": ("ตู้เก็บแผ่นตัวอย่างลามิเนต",          "7970 x 250 x 1200 มม. (852 ช่อง)"),
    "B9": ("ตู้ PANTRY เข้ามุม L",                "2450 x 600/400 x 2800 มม."),
}

for c in ITEMS:
    print(f"{c:4s} CASE A {t.price(c,'A',slots={'B7':852}.get(c,0)):>10,.0f}   "
          f"CASE B {t.price(c,'B',slots={'B7':852}.get(c,0)):>10,.0f}")

out = t.build(os.path.join(os.path.dirname(__file__), "example_output.xlsx"),
              items=ITEMS, slots={"B7": 852},
              title="ตัวอย่างถอดแบบ craft-boq",
              notes=["ไฟล์นี้เป็นตัวอย่างการใช้งาน ไม่ใช่ราคาจริงของโครงการใด"])
print("\nสร้างไฟล์:", out)
