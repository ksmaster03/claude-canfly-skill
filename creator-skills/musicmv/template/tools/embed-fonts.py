"""Inline the Sarabun TTFs into src/fonts-data.ts as data URIs.

Run once after copying the fonts into public/fonts/. Fetching the faces over the
bundled static server works for stills and short frame ranges but leaves
delayRender hanging on a full-length render, which kills it with no useful error.

    python tools/embed-fonts.py
"""
import base64
import io
import os

PAIRS = [("Sarabun-Regular.ttf", "SARABUN_REGULAR"),
         ("Sarabun-SemiBold.ttf", "SARABUN_SEMIBOLD")]

out = ["// Generated by tools/embed-fonts.py — do not edit by hand.", ""]
for name, var in PAIRS:
    data = open(os.path.join("public/fonts", name), "rb").read()
    out.append(f"export const {var} = 'data:font/ttf;base64,{base64.b64encode(data).decode()}';")
    out.append("")
io.open("src/fonts-data.ts", "w", encoding="utf-8").write("\n".join(out))
print("wrote src/fonts-data.ts")
