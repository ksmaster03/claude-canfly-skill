"""Embed a Thai-capable display face as base64 into src/fonts.ts.

    python tools/embed-fonts.py <font-dir> [Family]

Why embed rather than link: a webfont fetch inside every render chunk is one
more thing that can hold a delayRender() open, and the failure mode is a stalled
render rather than an obvious error.

Why a Thai face at all: the template shipped with an Arial Black stack, which
has no Thai glyphs. On a Thai song that renders the entire lyric as tofu boxes,
and it looks like a font-weight problem rather than a missing script.
"""
import base64
import os
import sys

NL = chr(10)
SRC = sys.argv[1] if len(sys.argv) > 1 else 'src/fonts'
FAMILY = sys.argv[2] if len(sys.argv) > 2 else 'Sarabun'
WEIGHTS = [(800, 'ExtraBold'), (700, 'Bold'), (600, 'SemiBold')]

css = []
for weight, name in WEIGHTS:
    path = os.path.join(SRC, f'{FAMILY}-{name}.ttf')
    if not os.path.exists(path):
        print('skip (missing): ' + path)
        continue
    b64 = base64.b64encode(open(path, 'rb').read()).decode()
    css.append("@font-face{font-family:'%s';font-weight:%d;font-style:normal;"
               "font-display:block;src:url(data:font/ttf;base64,%s) format('truetype');}"
               % (FAMILY, weight, b64))

if not css:
    raise SystemExit('no font files found in ' + SRC)

body = NL.join([
    '/**',
    ' * ' + FAMILY + ', embedded as base64. Generated by tools/embed-fonts.py.',
    ' *',
    ' * Mount <Fonts/> in every composition. Do not edit by hand.',
    ' */',
    'export const FONT_CSS = "' + ''.join(css).replace('"', '\\"') + '";',
    '',
])
open('src/fonts.ts', 'w', encoding='utf-8').write(body)
print('src/fonts.ts  %.2f MB  (%d faces)' % (os.path.getsize('src/fonts.ts') / 1e6, len(css)))
