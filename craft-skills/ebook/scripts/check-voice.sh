#!/usr/bin/env bash
# check-voice.sh — วัดความ "เป็นมนุษย์" ของแต่ละบท
# เกณฑ์: ตัวเชื่อมภาษาพูดรวม 15–29 จุด/บท · เอ่อ+เอิ่ม 0–2 · คำถาม ≥10 · **ขีดยาว ≤12**
# ⚠ ขีดยาว ` — ` เป็นลายเซ็น AI ที่ชัดที่สุด — เกิน 12 จุด/บท ถือว่าตก ให้แทนด้วยการตัดประโยค
#   หรือคำเชื่อม (ดังนั้น / เพราะว่า / ก็คือ / นั่นคือ / แปลว่า / ซึ่ง) หรือวงเล็บ
# ใช้: bash check-voice.sh <proj>
cd "${1:-.}"
CONN=("คือว่า" "คืออย่างนี้" "คือแบบนี้" "จริง ๆ แล้ว" "เอาจริง ๆ" "ความจริงคือ" "พูดตรง ๆ" "ทีนี้" "แบบว่า" "ประมาณว่า" "พูดง่าย ๆ" "เพราะฉะนั้น" "แปลว่า" "ก็เลยกลายเป็นว่า" "สรุปคือ" "อะไรทำนองนี้" "ดังนั้น" "แบบนี้" "แบบนั้น" "ก็คือ" "นั่นคือ")
DASH_MAX=12
printf "%-6s %8s %6s %6s %6s %6s   %s\n" บท ไบต์ เชื่อม เอ่อ คำถาม ขีดยาว สถานะ
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

for i in $(seq -w 1 16); do
  f="raw/ch$i.md"; [ -f "$f" ] || continue
  # นับเฉพาะ "ร้อยแก้วที่แก้ได้" — ตัดบล็อกโค้ดและหัวข้อแหล่งอ้างอิงท้ายบทออกก่อน
  # (ขีดยาวในสองโซนนี้ถูกสั่งห้ามแตะ ถ้านับรวมจะฟ้องผิดทั้งที่เนื้อความสะอาดแล้ว)
  awk '/^```/{inc=!inc; next} inc{next} /^## *(แหล่งอ้างอิง|บรรณานุกรม|อ้างอิง)/{stop=1} stop{next} {print}' "$f" > "$TMP"
  tot=0
  for w in "${CONN[@]}"; do n=$(grep -o "$w" "$TMP" | wc -l); tot=$((tot+n)); done
  uh=$(grep -o "เอ่อ\|เอิ่ม" "$TMP" | wc -l)
  q=$(grep -o "?\|หรือเปล่า\|ไหม" "$TMP" | wc -l)
  dash=$(grep -o " — " "$TMP" | wc -l)
  sz=$(stat -c%s "$f")
  if   [ "$tot" -lt 15 ]; then st="ตัวเชื่อมน้อยไป (ต้องรอบสอง)"
  elif [ "$tot" -gt 30 ]; then st="ตัวเชื่อมเยอะไป"
  elif [ "$dash" -gt "$DASH_MAX" ]; then st="ขีดยาวเยอะไป (>$DASH_MAX ต้องรอบสอง)"
  else st="ผ่าน"; fi
  printf "ch%-4s %8d %6d %6d %6d %6d   %s\n" "$i" "$sz" "$tot" "$uh" "$q" "$dash" "$st"
done
